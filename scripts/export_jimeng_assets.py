def main() -> None:
    rows = []
    for line in open(SCORES, encoding='utf-8'):
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            pass
    winners = [r for r in rows if r.get('score', -1) >= 9 and r.get('keep') and r['key'] in META]
    winners.sort(key=lambda r: (-r['score'], list(META).index(r['key'])))
    picked = winners[:N_PICK]
    print(f'≥9 分 {len(winners)} 个，取前 {len(picked)} 个：')
    for r in picked:
        print(f"  {r['score']}  {META[r['key']][0]}  ({r['key']})")

    OUT_DIR.mkdir(exist_ok=True)
    entries = []
    for r in picked:
        stem = r['key']
        name, ptype, extra_tags, form = META[stem]
        png = SRC / f'{stem}.png'
        webp = OUT_DIR / f'{stem}.webp'
        im = Image.open(png).convert('RGB')
        im.thumbnail((1024, 1024))
        buf = io.BytesIO()
        im.save(buf, 'WEBP', quality=88)
        webp.write_bytes(buf.getvalue())
        tags = [ptype, *extra_tags, '即梦']
        entries.append({
            'id': _pid(stem),
            'name': name, 'type': ptype, 'tags': tags,
            'image': f'/patterns/jimeng/{stem}.webp',
            'form': form,
        })
        print(f'  webp {webp.name} {len(buf.getvalue()) // 1024}KB')

    lines = [
        '// Auto-generated by scripts/export_jimeng_assets.py — 即梦 AI 生成、',
        '// glm-4v-flash 打分 ≥9 的精选纹样。并入 AI 元素库（免费拼贴素材，不入抽卡池）。',
        '// Do not edit by hand.',
        "import type { Pattern } from '../store/patternData'",
        '',
        'export const JIMENG_PATTERNS: Pattern[] = [',
    ]
    for e in entries:
        tag_str = ', '.join(f"'{t}'" for t in e['tags'])
        lines.append(
            f"  {{ id: '{e['id']}', name: '{e['name']}', type: '{e['type']}', "
            f"series: 'ai', rarity: 'ssr', tags: [{tag_str}], image: '{e['image']}', form: '{e['form']}' }},"
        )
    lines.append(']')
    TS_OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'-> {TS_OUT} ({len(entries)} entries)')


def _pid(stem: str) -> str:
    # 与 publish_patterns.py MANIFEST 的 patternId 保持一致
    # 文件名缩写 -> 发布 id 前缀（下划线后缀去掉）
    special = {
        'yunlei_ring': 'yunlei', 'feng_shang': 'feng', 'xixiangfeng': 'xixiang',
        'piqiuhua': 'piqiu', 'zhezhi_mudan': 'zhezhi', 'haishui_jiangya': 'haishui',
        'lianban_tang': 'lianban', 'suihansanyou': 'suihan',
    }
    return special.get(stem, stem) + '-1'


